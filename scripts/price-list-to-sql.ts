/**
 * Dev helper: turns a vendor price list (sheets exported as JSON rows) into a SQL file that
 * calls import_price_list() for one company. The app's Settings > Price lists screen does the
 * same thing from an uploaded .xlsx; this script exists for local seeding and tests.
 *
 *   pnpm tsx scripts/price-list-to-sql.ts <sheets.json> <vendor> <multiplier> <list name> <effective date> > out.sql
 *   pnpm tsx scripts/price-list-to-sql.ts supabase/pending/seed/timberpeak-msrp-sheets.json TimberPeak 0.33 "TimberPeak MSRP 2026" 2026-10-23
 *
 * The SQL expects a psql variable :company_id.
 */
import { readFileSync } from 'node:fs';
import { parsePriceList, toImportPayload, type SheetRows } from '../lib/estimating/vendorImport';

const [file, vendor, mult, listName, effective] = process.argv.slice(2);
if (!file || !vendor || !mult || !listName || !effective) {
  console.error('usage: price-list-to-sql <sheets.json> <vendor> <multiplier> <list name> <effective date>');
  process.exit(1);
}
const sheets = JSON.parse(readFileSync(file, 'utf8')) as SheetRows[];
const { collections, warnings } = parsePriceList(sheets, { vendor, costMultiplier: Number(mult) });

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`;
const lines: string[] = [];
lines.push(`-- Generated by scripts/price-list-to-sql.ts from ${file}`);
lines.push(`-- ${collections.length} color groups, ${collections.reduce((n, c) => n + c.items.length, 0)} items, cost = list x ${mult}`);
lines.push(`-- ${warnings.length} warnings to review with the vendor:`);
for (const w of warnings) lines.push(`--   [${w.kind}] ${w.sheet}: ${w.message}`);
lines.push(
  `select * from public.import_price_list(:'company_id'::uuid, ${lit(vendor)}, ${lit(listName)}, ${Number(mult)}, ` +
    `date ${lit(effective)}, ${lit(file.split('/').pop() ?? file)}, ${lit(JSON.stringify(toImportPayload(collections)))}::jsonb);`,
);
process.stdout.write(lines.join('\n') + '\n');
