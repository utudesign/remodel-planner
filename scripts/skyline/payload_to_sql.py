"""Skyline payload → SQL (like scripts/price-list-to-sql.ts does for TimberPeak).
  python3 -I scripts/skyline/payload_to_sql.py supabase/seed/skyline-springforest-2026.json            > supabase/seed/skyline_springforest_2026.sql   (psql var :company_id)
  python3 -I scripts/skyline/payload_to_sql.py supabase/seed/skyline-springforest-2026.json <uuid>     > supabase/seed_skyline_demo.sql
"""
import json, sys

p = json.load(open(sys.argv[1]))
company = f"'{sys.argv[2]}'::uuid" if len(sys.argv) > 2 else ":'company_id'::uuid"
lit = lambda s: "'" + str(s).replace("'", "''") + "'"
n = sum(len(c["items"]) for c in p["collections"])
print(f"-- Generated by scripts/skyline/payload_to_sql.py from {sys.argv[1].split('/')[-1]}")
print(f"-- {p['list_name']}: {len(p['collections'])} color groups, {len(p['colors'])} colors, {n} items, cost = list x {p['cost_multiplier']}")
cols = [{k: v for k, v in c.items()} for c in p["collections"]]
print(f"select * from public.import_price_list({company}, {lit(p['vendor'])}, {lit(p['list_name'])}, {p['cost_multiplier']}, "
      f"date {lit(p['effective_date'])}, {lit(p['source_file'])}, {lit(json.dumps(cols, separators=(',', ':')))}::jsonb);")
print(f"select public.import_brand_colors({company}, {lit(p['list_name'])}, {lit(json.dumps(p['colors'], separators=(',', ':')))}::jsonb);")
print(f"select public.sync_collection_colors({company});")
